import { assert, load } from './runtime.mjs';
const m = await load('server/index.ts');
const start = m.create(100);
const first = m.advance(start, 1100, { action: true, level: false });
assert.equal(first.actionMs, 1000);
assert.equal(first.levelMs, 0);
assert.deepEqual(m.advance(first, 50, { action: true, level: true }), first);
const paused = m.advance(first, 2100, { action: false, level: false });
assert.equal(paused.actionMs, 1000);
assert.equal(start.actionMs, 0);
const timer = m.startDecision(start, { decisionSeconds: 2, onTimeout: 'check-or-fold' }, { settleMs: 500 });
assert.deepEqual(timer, { settleUntil: 500, deadline: 2500 });
assert.equal(m.timeoutAction({ onTimeout: 'check-or-fold' }, true), 'check');
assert.equal(m.timeoutAction({ onTimeout: 'check-or-fold' }, false), 'fold');
const web = await load('web/index.ts');
assert.equal(web.remaining(500, 1000, 1600, false), 0);
assert.equal(web.remaining(500, 1000, 1600, true), 500);
assert.equal(web.remaining(null, 1000, 1600, false), null);
assert.equal(web.formatClock(60001), '1:01');
