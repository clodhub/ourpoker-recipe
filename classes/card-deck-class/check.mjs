import { assert, load } from './runtime.mjs';
const m = await load('server/index.ts');
const deck = m.createDeck();
assert.equal(deck.draw.length, 52);
assert.equal(new Set(deck.draw).size, 52);
const saved = structuredClone(deck);
const dealt = m.deal(deck, 7);
assert.equal(dealt.cards.length, 7);
assert.equal(m.remaining(dealt.deck), 45);
assert.equal(new Set([...dealt.cards, ...dealt.deck.draw]).size, 52);
assert.deepEqual(deck, saved);
assert.throws(() => m.deal(deck, 53));
assert.throws(() => m.deal(deck, -1));
assert.equal(m.createDeck({ decks: 2, jokers: true }).draw.length, 108);
assert.equal(m.parseCard('invalid'), null);
assert.equal(m.cardName('As'), 'ace of spades');
const web = await load('web/index.ts');
assert.equal(web.cardFacts('Ah').red, true);
assert.equal(web.cardFacts('As').red, false);
assert.equal(web.rankLabel('T'), '10');
