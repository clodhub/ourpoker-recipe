import { assert, load } from './runtime.mjs';
import { ledger } from './ledger.mjs';
const m = await load('web/index.ts');
const range = { min: 50, max: 500, opening: true };
assert.equal(m.snap(123, range, 25), 125);
assert.equal(m.snap(999, range, 25), 500);
assert.equal(m.snap(1, range, 25), 50);
assert.equal(m.isAllowedAmount(50, range), true);
assert.equal(m.isAllowedAmount(501, range), false);
assert.equal(m.callIsAllIn(100, 100), true);
assert.equal(m.callIsAllIn(50, 100), false);
assert.equal(m.betIsAllIn(150, 100, 50), true);
const server = await load('server/index.ts');
const ranking = new Proxy({}, { get() { throw new Error('an uncontested hand does not rank cards'); } });
const rules = server.createHoldem({ ledger, ranking }, { seats: 2 });
const cards = [...'23456789TJQKA'].flatMap(rank => [...'cdhs'].map(suit => rank + suit));
const input = { no: 1, level: 1, sb: 25, bb: 50, players: [{ id: 'a', seat: 0, stack: 1000 }, { id: 'b', seat: 1, stack: 1000 }], positions: null, deck: cards, rng: () => 0 };
const started = rules.newHand(input);
assert.equal(started.ok, true);
const hand = started.value.hand;
const snapshot = structuredClone(hand);
assert.equal(hand.actorId, 'a');
assert.equal(rules.legalActions(hand, 'a').call, 25);
assert.equal(rules.apply(hand, 'b', { type: 'fold' }).code, 'notYourTurn');
assert.equal(rules.apply(hand, 'a', { type: 'check' }).code, 'notAllowed');
const visible = rules.view(hand, 'a');
assert.equal(visible.players.find(player => player.id === 'a').cards.filter(Boolean).length, 2);
assert.deepEqual(visible.players.find(player => player.id === 'b').cards, [null, null]);
const folded = rules.apply(hand, 'a', { type: 'fold' });
assert.equal(folded.ok, true);
assert.equal(rules.isHandOver(folded.hand), true);
assert.equal(folded.hand.result.uncontested, true);
assert.deepEqual(rules.stacks(folded.hand), { a: 975, b: 1025 });
assert.equal(rules.chipsInPlay(folded.hand), 2000);
assert.deepEqual(hand, snapshot);
assert.equal(rules.parseAction({ type: 'bet', to: 'many' }).ok, false);
